-- ----------------------------------------------------------------------------
-- Customers
-- ----------------------------------------------------------------------------

CREATE INDEX ix_customers_status
    ON customers (status);

CREATE INDEX ix_customers_branch_id
    ON customers (branch_id);

CREATE INDEX ix_customers_email
    ON customers (email);


-- ----------------------------------------------------------------------------
-- Customer Addresses
-- ----------------------------------------------------------------------------

CREATE INDEX ix_customer_addresses_customer_id
    ON customer_addresses (customer_id);

CREATE INDEX ix_customer_addresses_customer_address_type
    ON customer_addresses (customer_id, address_type);


-- ----------------------------------------------------------------------------
-- Onboarding Applications
-- ----------------------------------------------------------------------------

CREATE INDEX ix_onboarding_applications_customer_id
    ON onboarding_applications (customer_id);

CREATE INDEX ix_onboarding_applications_status
    ON onboarding_applications (status);

CREATE INDEX ix_onboarding_applications_status_created_at
    ON onboarding_applications (status, created_at);


-- ----------------------------------------------------------------------------
-- Outbox
-- ----------------------------------------------------------------------------
--
-- The Outbox Publisher will normally search for records where
-- published_at IS NULL, ordered by occurred_at.
--
-- ----------------------------------------------------------------------------

-- Unpublished messages are the primary polling workload of the
-- Outbox Publisher. A partial index keeps this index focused on the
-- rows that still need to be published.
CREATE INDEX ix_outbox_messages_unpublished
    ON outbox_messages (occurred_at)
    WHERE published_at IS NULL;

CREATE INDEX ix_outbox_messages_aggregate
    ON outbox_messages (aggregate_type, aggregate_id);


-- ----------------------------------------------------------------------------
-- Inbox
-- ----------------------------------------------------------------------------

CREATE INDEX ix_inbox_messages_message_id
    ON inbox_messages (message_id);


